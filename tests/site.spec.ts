test('illustrations and educational feedback survive WebGL unavailability', async ({page}) => {
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    Object.defineProperty(HTMLCanvasElement.prototype,'getContext',{value:function(this: HTMLCanvasElement, type: string, ...args: unknown[]) {
      if (type.startsWith('webgl')) return null
      return Reflect.apply(original,this,[type,...args])
    }})
  })
  await page.goto('/chapter/3')
  await page.locator('.custody-demo').getByRole('button',{name:'Autocustódia',exact:true}).click()
  await expect(page.locator('.scene-custody img')).toBeVisible()
  await expect(page.locator('.scene-custody canvas')).toHaveCount(0)
  await expect(page.locator('#custody-explanation')).toContainText('A chave está com você.')
})
