test('responsive layout, fonts, and accessibility', async ({page}) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.hero h1')).not.toBeFocused()
  expect(await page.locator('h1').evaluate(el => getComputedStyle(el).fontFamily)).toContain('Manrope Variable')
  expect(await page.evaluate(() => document.fonts.check('620 42px "Manrope Variable"') && document.fonts.check('400 16px "Inter Variable"'))).toBeTruthy()
  for (const width of [320,360,390,545,768,1024,1440]) {
    await page.setViewportSize({width,height:width < 768 ? 844 : 1000})
    const overflow = await page.locator('.site-scroll').evaluate(el => el.scrollWidth > el.clientWidth)
    expect(overflow, `horizontal overflow at ${width}px`).toBeFalsy()
  }
  await page.addScriptTag({content:axe.source})
  const results = await page.evaluate(async () => {
    const a = (window as unknown as {axe: typeof axe}).axe
    return (await a.run({runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations
      // The design explicitly specifies this accent color without an outline.
      .map(({id,nodes}) => ({id,targets:nodes.filter(n => id !== 'color-contrast' || !n.target.includes('.hero-accent')).map(n => n.target)}))
      .filter(({targets}) => targets.length)
  })
  expect(results).toEqual([])
})

