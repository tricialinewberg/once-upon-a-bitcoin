test('the chapter coin falls back on context loss', async ({page}) => {
  await page.goto('/chapter/2')
  const scene = page.locator('.scene-coin')
  await scene.scrollIntoViewIfNeeded()
  const canvas = scene.locator('canvas')
  await expect(canvas).toBeVisible({timeout:25000})
  const lost = await canvas.evaluate(el => {
    const extension = (el as HTMLCanvasElement).getContext('webgl2')?.getExtension('WEBGL_lose_context')
    extension?.loseContext()
    return Boolean(extension)
  })
  expect(lost).toBeTruthy()
  await expect(scene.locator('img')).toBeVisible()
  await expect(scene.getByRole('status')).toContainText('A visualização 3D está indisponível')
})

